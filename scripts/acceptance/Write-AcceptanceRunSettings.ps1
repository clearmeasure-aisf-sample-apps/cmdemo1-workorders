<#
.SYNOPSIS
  Writes AcceptanceTests.runsettings NumberOfTestWorkers from the runner's core count.

.DESCRIPTION
  Default LevelOfParallelism / workers is 4 on a 4-core GitHub-hosted runner. Call this
  before `dotnet test` when the runner core count differs. Does not loosen any gates.
#>
[CmdletBinding()]
param(
    [string]$OutputPath = "",
    [int]$Workers = 0
)

$ErrorActionPreference = "Stop"

if ($Workers -le 0) {
    $Workers = [Math]::Max(1, [int]$env:NUMBER_OF_PROCESSORS)
    if ($Workers -le 0) { $Workers = [Environment]::ProcessorCount }
}

if ([string]::IsNullOrWhiteSpace($OutputPath)) {
    $repoRoot = Resolve-Path (Join-Path $PSScriptRoot "../..")
    $OutputPath = Join-Path $repoRoot "src/AcceptanceTests/AcceptanceTests.runsettings"
}

$xml = @"
<?xml version="1.0" encoding="utf-8"?>
<RunSettings>
  <NUnit>
    <!-- Generated by scripts/acceptance/Write-AcceptanceRunSettings.ps1 from runner cores ($Workers). -->
    <NumberOfTestWorkers>$Workers</NumberOfTestWorkers>
  </NUnit>
  <LoggerRunSettings>
    <Loggers>
      <Logger friendlyName="console" enabled="True">
        <Configuration>
          <Verbosity>normal</Verbosity>
        </Configuration>
      </Logger>
    </Loggers>
  </LoggerRunSettings>
</RunSettings>
"@

Set-Content -LiteralPath $OutputPath -Value $xml -Encoding utf8
Write-Host "Wrote NumberOfTestWorkers=$Workers to $OutputPath"
