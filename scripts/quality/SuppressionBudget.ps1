# Dot-source only. Scans C# and Razor under a root for suppression directives and task markers.
# A suppression is a `#pragma warning disable`, `// ReSharper disable`, or SuppressMessage attribute.
# It has a reason on the same line (`--` text, a trailing // comment, or Justification = "...")
# or on the nearest preceding comment. The committed maxSuppressions count may fall, not rise.

function Test-SuppressionBudgetSkippedPath {
    param(
        [Parameter(Mandatory = $true)][string]$FullName,
        [Parameter(Mandatory = $true)][string[]]$SkipSegments
    )

    $parts = $FullName -split '[\\/]'
    foreach ($part in $parts) {
        if ($SkipSegments -contains $part) {
            return $true
        }
    }

    return $false
}

function Get-SuppressionBudgetFiles {
    param([Parameter(Mandatory = $true)][string]$SourceRoot)

    $extensions = @('.cs', '.razor', '.cshtml')
    $skip = @('bin', 'obj', 'node_modules', 'TestResults')
    return @(Get-ChildItem -LiteralPath $SourceRoot -Recurse -File |
        Where-Object {
            ($extensions -contains $_.Extension) -and
            -not (Test-SuppressionBudgetSkippedPath -FullName $_.FullName -SkipSegments $skip)
        } |
        Sort-Object -Property FullName)
}

function Remove-SuppressionBudgetBom {
    param([AllowEmptyString()][string]$Line)

    if ($Line.Length -gt 0 -and $Line[0] -eq [char]0xFEFF) {
        return $Line.Substring(1)
    }

    return $Line
}

function Get-SuppressionKind {
    param([string]$Line)

    if ([string]::IsNullOrEmpty($Line)) { return '' }
    if ($Line -match '^\s*#pragma\s+warning\s+disable\b') { return 'pragma' }
    if ($Line -match '^\s*//\s*ReSharper\s+disable\b') { return 'resharper' }

    $trim = $Line.TrimStart()
    $isComment = $trim.StartsWith('//') -or $trim.StartsWith('/*') -or $trim.StartsWith('*')
    if (-not $isComment -and $Line -match 'SuppressMessage\s*\(') { return 'suppress' }
    return ''
}

function Get-SuppressionCommentBody {
    param([Parameter(Mandatory = $true)][string]$Line)

    $text = $Line.Trim()
    if ($text.StartsWith('///')) { return $text.Substring(3).Trim() }
    if ($text.StartsWith('//')) { return $text.Substring(2).Trim() }
    if ($text.StartsWith('/*')) {
        $inner = $text.Substring(2).Trim()
        if ($inner.EndsWith('*/')) { return $inner.Substring(0, $inner.Length - 2).Trim() }
        return $inner
    }

    if ($text.StartsWith('*')) { return $text.Substring(1).Trim() }
    return $null
}

function Test-SuppressionBoilerplate {
    param([Parameter(Mandatory = $true)][string]$Body)

    $text = $Body.Trim()
    if ($text -match '^</?auto-generated>$') { return $true }
    if ($text.Contains('DO NOT EDIT')) { return $true }
    if ($text.StartsWith('source:')) { return $true }
    if ($text.StartsWith('Generated by the protocol buffer compiler')) { return $true }
    return $false
}

function Test-PrecedingSuppressionReason {
    param([string]$Previous)

    if ([string]::IsNullOrWhiteSpace($Previous)) { return $false }
    if ((Get-SuppressionKind -Line $Previous) -ne '') { return $false }

    $body = Get-SuppressionCommentBody -Line $Previous
    if ([string]::IsNullOrWhiteSpace($body)) { return $false }
    if (Test-SuppressionBoilerplate -Body $body) { return $false }
    return $true
}

function Get-SuppressMessageSpan {
    param(
        [Parameter(Mandatory = $true)]$Lines,
        [Parameter(Mandatory = $true)][int]$Index
    )

    $parts = New-Object System.Collections.Generic.List[string]
    $last = [Math]::Min($Lines.Count - 1, $Index + 12)
    for ($cursor = $Index; $cursor -le $last; $cursor++) {
        $parts.Add($Lines[$cursor])
        if ($Lines[$cursor].Contains(']')) { break }
    }

    return ($parts -join "`n")
}

function Test-SuppressMessageJustification {
    param([string]$Span)

    if ([string]::IsNullOrWhiteSpace($Span)) { return $false }
    if ($Span -notmatch 'Justification\s*=\s*"([^"]*)"') { return $false }
    return -not [string]::IsNullOrWhiteSpace($Matches[1])
}

function Test-SuppressionHasReason {
    param(
        [Parameter(Mandatory = $true)][string]$Kind,
        [Parameter(Mandatory = $true)][string]$Line,
        [string]$Previous,
        [string]$Span
    )

    $sameLine = $false
    if ($Kind -eq 'resharper' -and $Line -match '--\s*\S') { $sameLine = $true }
    if ($Kind -eq 'pragma' -and $Line -match '#pragma\s+warning\s+disable\b.*//\s*\S') { $sameLine = $true }
    if ($Kind -eq 'suppress' -and (Test-SuppressMessageJustification -Span $Span)) { $sameLine = $true }
    if ($sameLine) { return $true }
    return Test-PrecedingSuppressionReason -Previous $Previous
}

function Get-PreviousNonBlankLine {
    param(
        [Parameter(Mandatory = $true)]$Lines,
        [Parameter(Mandatory = $true)][int]$Index
    )

    for ($cursor = $Index - 1; $cursor -ge 0; $cursor--) {
        if (-not [string]::IsNullOrWhiteSpace($Lines[$cursor])) {
            return $Lines[$cursor]
        }
    }

    return $null
}

function Get-TaskMarkerToken {
    param([string]$Line)

    if ($Line -match '\b(TODO|FIXME|HACK)\b') { return $Matches[1] }
    return ''
}

function Add-SuppressionFinding {
    param(
        [Parameter(Mandatory = $true)]$Findings,
        [Parameter(Mandatory = $true)][string]$Kind,
        [Parameter(Mandatory = $true)][string]$Location,
        [Parameter(Mandatory = $true)]$Detail
    )

    $colon = $Location.LastIndexOf(':')
    $Findings.Add([pscustomobject]@{
        Kind = $Kind
        Token = [string]$Detail.Token
        HasReason = [bool]$Detail.HasReason
        Path = $Location.Substring(0, $colon)
        Line = [int]$Location.Substring($colon + 1)
        Text = [string]$Detail.Text
    }) | Out-Null
}

function Get-FileSuppressionFindings {
    param(
        [Parameter(Mandatory = $true)][string]$RelativePath,
        [Parameter(Mandatory = $true)]$Lines
    )

    $findings = New-Object System.Collections.ArrayList
    for ($index = 0; $index -lt $Lines.Count; $index++) {
        Add-LineSuppressionFindings -Findings $findings -Lines $Lines -Index $index -RelativePath $RelativePath
    }

    return @($findings.ToArray())
}

function Add-LineSuppressionFindings {
    param(
        [Parameter(Mandatory = $true)]$Findings,
        [Parameter(Mandatory = $true)]$Lines,
        [Parameter(Mandatory = $true)][int]$Index,
        [Parameter(Mandatory = $true)][string]$RelativePath
    )

    $line = $Lines[$Index]
    $kind = Get-SuppressionKind -Line $line
    if ($kind -ne '') {
        $span = $line
        if ($kind -eq 'suppress') { $span = Get-SuppressMessageSpan -Lines $Lines -Index $Index }
        $previous = Get-PreviousNonBlankLine -Lines $Lines -Index $Index
        $hasReason = Test-SuppressionHasReason -Kind $kind -Line $line -Previous $previous -Span $span
        $location = "${RelativePath}:$($Index + 1)"
        $detail = @{ Text = $line.Trim(); HasReason = [bool]$hasReason }
        Add-SuppressionFinding -Findings $Findings -Kind 'suppression' -Location $location -Detail $detail
    }

    $token = Get-TaskMarkerToken -Line $line
    if ($token -ne '') {
        $location = "${RelativePath}:$($Index + 1)"
        $detail = @{ Text = $line.Trim(); Token = $token }
        Add-SuppressionFinding -Findings $Findings -Kind 'marker' -Location $location -Detail $detail
    }
}

function Read-SuppressionBudgetLines {
    param([Parameter(Mandatory = $true)][string]$FullName)

    $lines = [System.IO.File]::ReadAllLines($FullName)
    $stripped = New-Object System.Collections.Generic.List[string]
    foreach ($line in $lines) {
        $stripped.Add((Remove-SuppressionBudgetBom -Line $line))
    }

    return ,$stripped
}

function Get-SuppressionBudgetReport {
    param(
        [Parameter(Mandatory = $true)][string]$SourceRoot,
        [Parameter(Mandatory = $true)][int]$MaxSuppressions
    )

    if (-not (Test-Path -LiteralPath $SourceRoot)) {
        throw "Source root not found: $SourceRoot"
    }

    $all = New-Object System.Collections.ArrayList
    foreach ($file in @(Get-SuppressionBudgetFiles -SourceRoot $SourceRoot)) {
        $relative = [System.IO.Path]::GetRelativePath($SourceRoot, $file.FullName).Replace('\', '/')
        $lines = Read-SuppressionBudgetLines -FullName $file.FullName
        foreach ($finding in @(Get-FileSuppressionFindings -RelativePath $relative -Lines $lines)) {
            $all.Add($finding) | Out-Null
        }
    }

    return New-SuppressionBudgetReport -Findings $all -MaxSuppressions $MaxSuppressions
}

function New-SuppressionBudgetReport {
    param(
        [Parameter(Mandatory = $true)]$Findings,
        [Parameter(Mandatory = $true)][int]$MaxSuppressions
    )

    $suppressions = @($Findings | Where-Object { $_.Kind -eq 'suppression' })
    $missing = @($suppressions | Where-Object { -not $_.HasReason })
    $markers = @($Findings | Where-Object { $_.Kind -eq 'marker' })
    $count = @($suppressions).Count
    $passed = ($missing.Count -eq 0 -and $markers.Count -eq 0 -and $count -le $MaxSuppressions)
    return [pscustomobject]@{
        SuppressionCount = $count
        MaxSuppressions = $MaxSuppressions
        MissingReasons = $missing
        TaskMarkers = $markers
        Passed = [bool]$passed
    }
}

function Read-SuppressionBudgetBaseline {
    param([Parameter(Mandatory = $true)][string]$Path)

    if (-not (Test-Path -LiteralPath $Path)) {
        throw "Suppression budget baseline not found: $Path"
    }

    $payload = Get-Content -LiteralPath $Path -Raw -Encoding utf8 | ConvertFrom-Json
    $max = 0
    $raw = if ($null -eq $payload) { '' } else { [string]$payload.maxSuppressions }
    if (-not [int]::TryParse($raw, [ref]$max) -or $max -lt 0) {
        throw "Suppression budget baseline must contain a non-negative integer maxSuppressions: $Path"
    }

    return $max
}

function Write-SuppressionBudgetResult {
    param([Parameter(Mandatory = $true)]$Report)

    $summary = "suppression budget passed: $($Report.SuppressionCount) suppression(s), baseline $($Report.MaxSuppressions)."
    if (-not $Report.Passed) {
        $summary = "suppression budget failed: $($Report.SuppressionCount) suppression(s), baseline $($Report.MaxSuppressions)."
    }

    Write-Output $summary
    if ($Report.Passed) { return }
    if ($Report.SuppressionCount -gt $Report.MaxSuppressions) {
        Write-Output "suppression count $($Report.SuppressionCount) exceeds baseline $($Report.MaxSuppressions)."
    }

    foreach ($missing in @($Report.MissingReasons)) {
        Write-Output "missing reason: $($missing.Path):$($missing.Line) $($missing.Text)"
    }

    foreach ($marker in @($Report.TaskMarkers)) {
        Write-Output "task marker $($marker.Token): $($marker.Path):$($marker.Line) $($marker.Text)"
    }
}
