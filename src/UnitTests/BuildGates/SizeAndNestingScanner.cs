using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace ClearMeasure.Bootcamp.UnitTests.BuildGates;

/// <summary>
/// One size or nesting violation. A file-length hit has no member name.
/// The key omits the measured size so an already-listed member can change length
/// without churning the ratchet. A new member, or a member that newly crosses a
/// limit, is a new key and fails the gate.
/// </summary>
internal sealed class SizeViolation(string rule, string relativePath, string? symbol)
{
    /// <summary>Which limit was crossed.</summary>
    public string Rule { get; } = rule;

    /// <summary>Stable baseline line.</summary>
    public string Key { get; } = symbol is null
        ? $"{rule} {relativePath}"
        : $"{rule} {relativePath} {symbol}";
}

/// <summary>
/// Scans hand-written <c>.cs</c> and <c>.razor</c> files. Razor files are gated on
/// length only: <c>@code</c> blocks mix markup with C#, so method rules run on
/// <c>.cs</c> syntax, including <c>.razor.cs</c> code-behinds.
/// </summary>
internal static class SizeAndNestingScanner
{
    /// <summary>Sorted violation keys for the hand-written sources of <paramref name="checkout"/>.</summary>
    public static IReadOnlyList<string> ScanRepository(RepositoryCheckout checkout)
    {
        var keys = new List<string>();
        foreach (var path in checkout.SourceFiles(".cs", ".razor"))
        {
            keys.AddRange(ScanFile(checkout.Relative(path), File.ReadAllText(path)).Select(violation => violation.Key));
        }

        keys.Sort(StringComparer.Ordinal);
        return keys;
    }

    /// <summary>Violations in one source file. <paramref name="relativePath"/> selects the file cap.</summary>
    public static IReadOnlyList<SizeViolation> ScanFile(string relativePath, string text)
    {
        var violations = new List<SizeViolation>();
        if (SizeAndNestingLimits.IsAutoGenerated(text))
        {
            return violations;
        }

        AddFileViolation(relativePath, text, violations);
        if (relativePath.EndsWith(".cs", StringComparison.OrdinalIgnoreCase))
        {
            AddMemberViolations(relativePath, text, violations);
        }

        return violations;
    }

    private static void AddFileViolation(
        string relativePath,
        string text,
        List<SizeViolation> violations)
    {
        var lines = SizeAndNestingLimits.CountLines(text);
        if (lines > SizeAndNestingLimits.FileLineLimit(relativePath))
        {
            violations.Add(new SizeViolation(SizeAndNestingLimits.FileRule, relativePath, null));
        }
    }

    private static void AddMemberViolations(
        string relativePath,
        string text,
        List<SizeViolation> violations)
    {
        var root = CSharpSyntaxTree.ParseText(text).GetRoot();
        var seen = new HashSet<string>(StringComparer.Ordinal);
        var context = new ScanBuffer(relativePath, violations, seen);
        foreach (var node in root.DescendantNodesAndSelf())
        {
            Inspect(context, node);
        }
    }

    private static void Inspect(ScanBuffer context, SyntaxNode node)
    {
        if (TryInspectCallable(context, node) || TryInspectSignature(context, node))
        {
            return;
        }

        InspectTypeOrTopLevel(context, node);
    }

    private static bool TryInspectCallable(ScanBuffer context, SyntaxNode node)
    {
        if (node is BaseMethodDeclarationSyntax method)
        {
            InspectCallable(context, method, method.ParameterList, HasBody(method));
            return true;
        }

        if (node is LocalFunctionStatementSyntax local)
        {
            InspectCallable(context, local, local.ParameterList, HasBody(local));
            return true;
        }

        if (node is AccessorDeclarationSyntax accessor)
        {
            InspectCallable(context, accessor, null, HasBody(accessor));
            return true;
        }

        return false;
    }

    private static bool TryInspectSignature(ScanBuffer context, SyntaxNode node)
    {
        if (node is PropertyDeclarationSyntax { ExpressionBody: not null } property)
        {
            InspectCallable(context, property, null, hasBody: true);
            return true;
        }

        if (node is IndexerDeclarationSyntax indexer)
        {
            InspectCallable(context, indexer, indexer.ParameterList, indexer.ExpressionBody != null);
            return true;
        }

        if (node is DelegateDeclarationSyntax del)
        {
            InspectCallable(context, del, del.ParameterList, hasBody: false);
            return true;
        }

        return false;
    }

    private static void InspectTypeOrTopLevel(ScanBuffer context, SyntaxNode node)
    {
        if (node is TypeDeclarationSyntax { ParameterList: not null } type)
        {
            InspectCallable(context, type, type.ParameterList, hasBody: false);
            return;
        }

        if (node is CompilationUnitSyntax unit)
        {
            InspectTopLevel(context, unit);
        }
    }

    private static void InspectCallable(
        ScanBuffer context,
        SyntaxNode member,
        BaseParameterListSyntax? parameters,
        bool hasBody)
    {
        var symbol = SymbolName.Format(member, parameters);
        if (parameters is { Parameters.Count: > SizeAndNestingLimits.MaxParameters })
        {
            context.Add(SizeAndNestingLimits.ParametersRule, symbol);
        }

        if (!hasBody)
        {
            return;
        }

        if (LineCount(member) > SizeAndNestingLimits.MethodLines)
        {
            context.Add(SizeAndNestingLimits.MethodRule, symbol);
        }

        if (NestingDepth.Measure(member) > SizeAndNestingLimits.MaxNesting)
        {
            context.Add(SizeAndNestingLimits.NestingRule, symbol);
        }
    }

    private static void InspectTopLevel(ScanBuffer context, CompilationUnitSyntax unit)
    {
        var statements = unit.Members.OfType<GlobalStatementSyntax>().ToArray();
        if (statements.Length == 0)
        {
            return;
        }

        const string symbol = "<top-level>()";
        if (TopLevelLines(statements) > SizeAndNestingLimits.MethodLines)
        {
            context.Add(SizeAndNestingLimits.MethodRule, symbol);
        }

        if (TopLevelNesting(statements) > SizeAndNestingLimits.MaxNesting)
        {
            context.Add(SizeAndNestingLimits.NestingRule, symbol);
        }
    }

    private static int TopLevelLines(GlobalStatementSyntax[] statements)
    {
        var start = statements[0].GetLocation().GetLineSpan().StartLinePosition.Line;
        var end = statements[^1].GetLocation().GetLineSpan().EndLinePosition.Line;
        return end - start + 1;
    }

    private static int TopLevelNesting(GlobalStatementSyntax[] statements)
    {
        var max = 0;
        foreach (var statement in statements)
        {
            var depth = NestingDepth.Measure(statement);
            if (depth > max)
            {
                max = depth;
            }
        }

        return max;
    }

    private static int LineCount(SyntaxNode node)
    {
        var span = node.GetLocation().GetLineSpan();
        return span.EndLinePosition.Line - span.StartLinePosition.Line + 1;
    }

    private static bool HasBody(BaseMethodDeclarationSyntax method)
    {
        return method.Body != null || method.ExpressionBody != null;
    }

    private static bool HasBody(LocalFunctionStatementSyntax local)
    {
        return local.Body != null || local.ExpressionBody != null;
    }

    private static bool HasBody(AccessorDeclarationSyntax accessor)
    {
        return accessor.Body != null || accessor.ExpressionBody != null;
    }

    private sealed class ScanBuffer(
        string relativePath,
        List<SizeViolation> violations,
        HashSet<string> seen)
    {
        public void Add(string rule, string symbol)
        {
            var violation = new SizeViolation(rule, relativePath, symbol);
            if (seen.Add(violation.Key))
            {
                violations.Add(violation);
            }
        }
    }
}
