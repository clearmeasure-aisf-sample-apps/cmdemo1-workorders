namespace ClearMeasure.Bootcamp.UnitTests.BuildGates;

/// <summary>
/// Limits for the size and nesting gate. Production files stay at or under
/// <see cref="ProductionFileLines"/> lines. Test projects use the looser
/// <see cref="TestFileLines"/> cap. Methods stay at or under
/// <see cref="MethodLines"/> lines and <see cref="MaxParameters"/> parameters.
/// Control-flow nesting stays at or under <see cref="MaxNesting"/>.
/// </summary>
internal static class SizeAndNestingLimits
{
    /// <summary>Maximum lines in a production <c>.cs</c> or <c>.razor</c> file.</summary>
    public const int ProductionFileLines = 300;

    /// <summary>Maximum lines in a file under a test project. Twice the production cap.</summary>
    public const int TestFileLines = 600;

    /// <summary>Maximum lines in a method, constructor, accessor, or local function.</summary>
    public const int MethodLines = 30;

    /// <summary>Maximum parameters on a method, constructor, indexer, or primary constructor.</summary>
    public const int MaxParameters = 4;

    /// <summary>Maximum nested control-flow depth. An <c>else if</c> does not add a level.</summary>
    public const int MaxNesting = 3;

    /// <summary>Baseline rule for an oversized file.</summary>
    public const string FileRule = "file";

    /// <summary>Baseline rule for a member whose span exceeds <see cref="MethodLines"/>.</summary>
    public const string MethodRule = "method";

    /// <summary>Baseline rule for a signature with more than <see cref="MaxParameters"/> parameters.</summary>
    public const string ParametersRule = "parameters";

    /// <summary>Baseline rule for control flow nested deeper than <see cref="MaxNesting"/>.</summary>
    public const string NestingRule = "nesting";

    /// <summary>Line limit for <paramref name="relativePath"/>.</summary>
    public static int FileLineLimit(string relativePath)
    {
        return IsTestFile(relativePath) ? TestFileLines : ProductionFileLines;
    }

    /// <summary>True when the path sits in a test project.</summary>
    public static bool IsTestFile(string relativePath)
    {
        var normalized = Normalize(relativePath);
        return ContainsSegment(normalized, "UnitTests")
            || ContainsSegment(normalized, "IntegrationTests")
            || ContainsSegment(normalized, "AcceptanceTests");
    }

    /// <summary>
    /// True for build output, generated source, and files that are not hand-written.
    /// </summary>
    public static bool IsExcluded(string relativePath)
    {
        var normalized = Normalize(relativePath);
        if (ContainsSegment(normalized, "bin")
            || ContainsSegment(normalized, "obj")
            || ContainsSegment(normalized, "Generated")
            || ContainsSegment(normalized, "TestResults"))
        {
            return true;
        }

        return normalized.EndsWith(".g.cs", StringComparison.OrdinalIgnoreCase)
            || normalized.EndsWith(".designer.cs", StringComparison.OrdinalIgnoreCase);
    }

    /// <summary>Editor line count. A trailing newline does not add an extra line.</summary>
    public static int CountLines(string text)
    {
        if (text.Length == 0)
        {
            return 0;
        }

        var normalized = text.Replace("\r\n", "\n", StringComparison.Ordinal).Replace('\r', '\n');
        var newlines = 0;
        foreach (var character in normalized)
        {
            if (character == '\n')
            {
                newlines++;
            }
        }

        return normalized[^1] == '\n' ? newlines : newlines + 1;
    }

    /// <summary>True when the header marks the file as generated.</summary>
    public static bool IsAutoGenerated(string text)
    {
        var head = text.Length <= 800 ? text : text[..800];
        return head.Contains("<auto-generated", StringComparison.OrdinalIgnoreCase)
            || head.Contains("<autogenerated", StringComparison.OrdinalIgnoreCase);
    }

    private static string Normalize(string relativePath)
    {
        return "/" + relativePath.Replace('\\', '/').TrimStart('/');
    }

    private static bool ContainsSegment(string normalized, string segment)
    {
        return normalized.Contains("/" + segment + "/", StringComparison.OrdinalIgnoreCase);
    }
}
