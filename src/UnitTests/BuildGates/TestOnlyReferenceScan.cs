using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace ClearMeasure.Bootcamp.UnitTests.BuildGates;

/// <summary>
/// Finds public and internal production members or types whose simple name appears only in test
/// projects (plus the declaration itself). Syntax-only, same style as
/// <c>SolutionArchitectureScan</c>: no compilation, ratchet keys only shrink. Mediator handler types are not
/// declarations here: the Mediator source generator registers them, so no hand-written code names them.
/// </summary>
internal static class TestOnlyReferenceScan
{
    private static readonly string[] TestProjectSegments = ["UnitTests", "IntegrationTests", "AcceptanceTests"];

    /// <summary>Baseline path for this gate.</summary>
    public const string BaselinePath = "src/UnitTests/BuildGates/test-only-reference-baseline.txt";

    /// <summary>
    /// Sorted keys <c>{path} :: {symbol}</c> for production declarations referenced only from tests.
    /// </summary>
    public static IReadOnlyList<string> ScanRepository(RepositoryCheckout checkout)
    {
        var sources = LoadSources(checkout);
        var index = BuildNameIndex(sources);
        var keys = new SortedSet<string>(StringComparer.Ordinal);
        foreach (var declaration in Declarations(sources))
        {
            if (IsReferencedOnlyFromTests(declaration, index))
            {
                keys.Add($"{declaration.RelativePath} :: {declaration.Symbol}");
            }
        }

        return keys.ToList();
    }

    private static IReadOnlyList<SourceFile> LoadSources(RepositoryCheckout checkout)
    {
        var files = new List<SourceFile>();
        foreach (var path in checkout.SourceFiles(".cs", ".razor"))
        {
            var relative = checkout.Relative(path);
            var text = File.ReadAllText(path);
            if (SizeAndNestingLimits.IsAutoGenerated(text))
            {
                continue;
            }

            files.Add(new SourceFile(relative, text, IsTestPath(relative)));
        }

        return files;
    }

    private static Dictionary<string, List<NameHit>> BuildNameIndex(IReadOnlyList<SourceFile> sources)
    {
        var index = new Dictionary<string, List<NameHit>>(StringComparer.Ordinal);
        foreach (var source in sources)
        {
            if (source.RelativePath.EndsWith(".cs", StringComparison.OrdinalIgnoreCase))
            {
                IndexCSharpIdentifiers(source, index);
            }
            else
            {
                IndexRazorWords(source, index);
            }
        }

        return index;
    }

    private static void IndexCSharpIdentifiers(SourceFile source, Dictionary<string, List<NameHit>> index)
    {
        var root = CSharpSyntaxTree.ParseText(source.Text).GetRoot();
        foreach (var node in root.DescendantNodes())
        {
            var name = IdentifierText(node);
            if (name is null)
            {
                continue;
            }

            AddHit(index, name, new NameHit(source.RelativePath, source.IsTest, node.SpanStart));
        }
    }

    private static void IndexRazorWords(SourceFile source, Dictionary<string, List<NameHit>> index)
    {
        var text = source.Text;
        var start = 0;
        while (start < text.Length)
        {
            if (!IsIdentifierStart(text[start]))
            {
                start++;
                continue;
            }

            var end = start + 1;
            while (end < text.Length && IsIdentifierPart(text[end]))
            {
                end++;
            }

            AddHit(index, text[start..end], new NameHit(source.RelativePath, source.IsTest, start));
            start = end;
        }
    }

    private static string? IdentifierText(SyntaxNode node) =>
        node switch
        {
            IdentifierNameSyntax identifier => identifier.Identifier.ValueText,
            GenericNameSyntax generic => generic.Identifier.ValueText,
            _ => null
        };

    private static void AddHit(Dictionary<string, List<NameHit>> index, string name, NameHit hit)
    {
        if (!index.TryGetValue(name, out var hits))
        {
            hits = [];
            index[name] = hits;
        }

        hits.Add(hit);
    }

    private static IEnumerable<Declaration> Declarations(IReadOnlyList<SourceFile> sources)
    {
        foreach (var source in sources)
        {
            if (source.IsTest || !source.RelativePath.EndsWith(".cs", StringComparison.OrdinalIgnoreCase))
            {
                continue;
            }

            var root = CSharpSyntaxTree.ParseText(source.Text).GetRoot();
            foreach (var declaration in DeclarationsIn(source.RelativePath, root))
            {
                yield return declaration;
            }
        }
    }

    private static IEnumerable<Declaration> DeclarationsIn(string relativePath, SyntaxNode root)
    {
        foreach (var node in root.DescendantNodes())
        {
            foreach (var declaration in DeclarationsAt(relativePath, node))
            {
                yield return declaration;
            }
        }
    }

    private static IEnumerable<Declaration> DeclarationsAt(string relativePath, SyntaxNode node) =>
        TypeDeclarationsAt(relativePath, node).Concat(MemberDeclarationsAt(relativePath, node));

    private static IEnumerable<Declaration> TypeDeclarationsAt(string relativePath, SyntaxNode node)
    {
        if (node is TypeDeclarationSyntax type && IsPublicOrInternalType(type) && !IsMediatorHandler(type))
        {
            yield return Named(relativePath, type.Identifier, type.Identifier.ValueText);
            yield break;
        }

        if (node is EnumDeclarationSyntax enumeration && IsVisible(enumeration.Modifiers, isTopLevel: true))
        {
            yield return Named(relativePath, enumeration.Identifier, enumeration.Identifier.ValueText);
            yield break;
        }

        if (node is DelegateDeclarationSyntax del && IsVisible(del.Modifiers, isTopLevel: true))
        {
            var arity = del.TypeParameterList?.Parameters.Count is > 0 and var count ? $"<{count}>" : "";
            yield return Named(relativePath, del.Identifier, del.Identifier.ValueText + arity);
        }
    }

    private static IEnumerable<Declaration> MemberDeclarationsAt(string relativePath, SyntaxNode node)
    {
        switch (node)
        {
            case MethodDeclarationSyntax method when IsScannedMethod(method):
                yield return Named(relativePath, method.Identifier, SymbolName.Format(method, method.ParameterList));
                break;
            case PropertyDeclarationSyntax property when IsVisibleMember(property.Modifiers, property.Parent):
                yield return Named(relativePath, property.Identifier, OwnerPrefix(property) + property.Identifier.ValueText);
                break;
            case FieldDeclarationSyntax field when IsVisibleMember(field.Modifiers, field.Parent):
                foreach (var variable in field.Declaration.Variables)
                {
                    yield return Named(relativePath, variable.Identifier, OwnerPrefix(field) + variable.Identifier.ValueText);
                }

                break;
            case EventDeclarationSyntax eventDecl when IsVisibleMember(eventDecl.Modifiers, eventDecl.Parent):
                yield return Named(relativePath, eventDecl.Identifier, OwnerPrefix(eventDecl) + eventDecl.Identifier.ValueText);
                break;
        }
    }

    private static bool IsScannedMethod(MethodDeclarationSyntax method) =>
        !method.Modifiers.Any(SyntaxKind.OverrideKeyword)
        && method.ExplicitInterfaceSpecifier is null
        && IsVisibleMember(method.Modifiers, method.Parent);

    private static Declaration Named(string relativePath, SyntaxToken identifier, string symbol) =>
        new(relativePath, identifier.ValueText, symbol, identifier.SpanStart);

    private static bool IsVisibleMember(SyntaxTokenList modifiers, SyntaxNode? parent) =>
        parent is InterfaceDeclarationSyntax || IsVisible(modifiers, isTopLevel: false);

    private static string OwnerPrefix(SyntaxNode node)
    {
        var type = node.Ancestors().OfType<TypeDeclarationSyntax>().FirstOrDefault();
        return type is null ? "" : type.Identifier.ValueText + ".";
    }

    private static readonly string[] MediatorHandlerInterfaces = ["IRequestHandler", "INotificationHandler"];

    /// <summary>
    /// A request or notification handler: the Mediator source generator references it from generated code, which this
    /// scan cannot see.
    /// </summary>
    private static bool IsMediatorHandler(TypeDeclarationSyntax type) =>
        type.BaseList?.Types.Any(baseType => baseType.Type is GenericNameSyntax generic
            && MediatorHandlerInterfaces.Contains(generic.Identifier.ValueText)) == true;

    private static bool IsPublicOrInternalType(TypeDeclarationSyntax type)
    {
        var isTopLevel = type.Parent is BaseNamespaceDeclarationSyntax or CompilationUnitSyntax or FileScopedNamespaceDeclarationSyntax;
        return IsVisible(type.Modifiers, isTopLevel);
    }

    private static bool IsVisible(SyntaxTokenList modifiers, bool isTopLevel)
    {
        if (modifiers.Any(SyntaxKind.PrivateKeyword) || modifiers.Any(SyntaxKind.ProtectedKeyword)
            || modifiers.Any(SyntaxKind.FileKeyword))
        {
            return false;
        }

        if (modifiers.Any(SyntaxKind.PublicKeyword) || modifiers.Any(SyntaxKind.InternalKeyword))
        {
            return true;
        }

        return isTopLevel;
    }

    private static bool IsReferencedOnlyFromTests(Declaration declaration, Dictionary<string, List<NameHit>> index)
    {
        if (!index.TryGetValue(declaration.SimpleName, out var hits))
        {
            return false;
        }

        var sawTest = false;
        foreach (var hit in hits)
        {
            if (hit.RelativePath == declaration.RelativePath && hit.SpanStart == declaration.SpanStart)
            {
                continue;
            }

            if (!hit.IsTest)
            {
                return false;
            }

            sawTest = true;
        }

        return sawTest;
    }

    private static bool IsTestPath(string relativePath)
    {
        var normalized = "/" + relativePath.Replace('\\', '/').TrimStart('/');
        foreach (var segment in TestProjectSegments)
        {
            if (normalized.Contains("/" + segment + "/", StringComparison.OrdinalIgnoreCase))
            {
                return true;
            }
        }

        return false;
    }

    private static bool IsIdentifierStart(char character) =>
        character is >= 'A' and <= 'Z' or >= 'a' and <= 'z' or '_' or '@';

    private static bool IsIdentifierPart(char character) =>
        IsIdentifierStart(character) || character is >= '0' and <= '9';

    private sealed record SourceFile(string RelativePath, string Text, bool IsTest);

    private sealed record NameHit(string RelativePath, bool IsTest, int SpanStart);

    private sealed record Declaration(string RelativePath, string SimpleName, string Symbol, int SpanStart);
}
